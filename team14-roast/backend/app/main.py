"""FastAPI application entrypoint."""
import logging
from typing import Annotated

from fastapi import Depends, FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from sqlalchemy import text
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session
from slowapi.middleware import SlowAPIMiddleware

from app.config import settings
from app.database import get_db
from app.exceptions import register_exception_handlers
from app.rate_limit import limiter
from app.routers.auth import router as auth_router
from app.routers.dashboard import router as dashboard_router
from app.routers.gallery import router as gallery_router
from app.routers.reactions import router as reactions_router
from app.routers.roasts import router as roasts_router
from app.routers.settings import router as settings_router

logging.basicConfig(
    level=logging.DEBUG if settings.DEBUG else logging.INFO,
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)

if settings.ROAST_PROVIDER == "fake":
    logger.warning("ROAST_PROVIDER=fake: roasts are canned dev output, not generated by an LLM.")
elif settings.ROAST_PROVIDER == "openai" and not settings.OPENAI_API_KEY:
    logger.warning("ROAST_PROVIDER=openai but OPENAI_API_KEY is not set: roasts will return 503.")
elif settings.ROAST_PROVIDER == "anthropic" and not settings.ANTHROPIC_API_KEY:
    logger.warning("ANTHROPIC_API_KEY is not set: roast generation will return 503 until it is.")

if not settings.GITHUB_TOKEN:
    logger.warning(
        "GITHUB_TOKEN is not set: unauthenticated GitHub API calls are limited to 60/hour."
    )

# debug is deliberately never enabled (it would return tracebacks to clients).
app = FastAPI(title=settings.APP_NAME, version="0.1.0", debug=False)
app.state.limiter = limiter
register_exception_handlers(app)

app.add_middleware(SlowAPIMiddleware)
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.CORS_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.get("/health", tags=["health"])
async def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/health/ready", tags=["health"])
def health_ready(db: Annotated[Session, Depends(get_db)]) -> dict[str, str]:
    """Readiness probe: verifies the database is reachable."""
    try:
        db.execute(text("SELECT 1"))
    except SQLAlchemyError:
        logger.exception("Readiness check failed")
        raise HTTPException(status_code=503, detail="Database unavailable") from None
    return {"status": "ready"}


app.include_router(auth_router, prefix=settings.API_V1_PREFIX)
app.include_router(roasts_router, prefix=settings.API_V1_PREFIX)
app.include_router(reactions_router, prefix=settings.API_V1_PREFIX)
app.include_router(gallery_router, prefix=settings.API_V1_PREFIX)
app.include_router(dashboard_router, prefix=settings.API_V1_PREFIX)
app.include_router(settings_router, prefix=settings.API_V1_PREFIX)
